def rows(trace: str) -> list[tuple[float, float, float, float]]:
    """(seconds, remaining, elapsed, rms) of each row of a trace."""
    found = []
    for line in trace.splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            seconds, remaining, elapsed, rms = (float(part) for part in line.split())
            found.append((seconds, remaining, elapsed, rms))
    return found
